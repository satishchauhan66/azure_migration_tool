"""Generate SQL Compare–style repair scripts from diff reports."""

from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

from ..backup.exporters import format_module_sql_single, wrap_create_or_alter
from ..utils.azure_compat import (
    EXPECTED_SKIP_REASONS,
    is_azure_nonportable_module,
    is_mi_blocked_framework_assembly_name,
    is_windows_principal_batch,
    is_windows_principal_name,
)
from ..utils.paths import qident, utc_ts_compact
from ..utils.sql import prepare_sql_batches

RepairItem = Dict[str, Any]


def _sql_compare_header(source: str, target: str) -> str:
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    return "\n".join(
        [
            "/*",
            f"Repair script generated by azure_migration_tool at {ts}",
            f"Synchronize: {target}",
            f"With:        {source}",
            "",
            "Patterns: DROP + CREATE OR ALTER (modules), CREATE ASSEMBLY (MI),",
            "optional DROP extra objects, Windows principals commented (Azure MI).",
            "*/",
            "SET NUMERIC_ROUNDABORT OFF",
            "GO",
            "SET ANSI_PADDING, ANSI_WARNINGS, CONCAT_NULL_YIELDS_NULL, ARITHABORT,",
            "     QUOTED_IDENTIFIER, ANSI_NULLS ON",
            "GO",
            "SET XACT_ABORT ON",
            "GO",
            "",
        ]
    )


def _sql_to_batches(sql_text: str) -> List[str]:
    if not (sql_text or "").strip():
        return []
    return [
        b.strip()
        for b in prepare_sql_batches(sql_text, file_type="SCHEMA_REPAIR")
        if b and b.strip()
    ]


def _repair_item(
    item_id: str,
    category: str,
    object_name: str,
    action: str,
    sql_text: str,
    *,
    expected_skip: bool = False,
    reason: str = "",
) -> RepairItem:
    return {
        "id": item_id,
        "category": category,
        "object_name": object_name,
        "action": action,
        "sql_batches": _sql_to_batches(sql_text),
        "expected_skip": expected_skip,
        "reason": reason or "",
    }


def _drop_module_core(schema: str, name: str, kind: str) -> str:
    full = f"{qident(schema)}.{qident(name)}"
    if kind == "VIEW":
        obj_type, drop_kw = "V", "VIEW"
    elif kind == "FUNCTION":
        obj_type, drop_kw = "FN", "FUNCTION"
    else:
        obj_type, drop_kw = "P", "PROCEDURE"
    return "\n".join(
        [
            f"IF OBJECT_ID(N'{full}', N'{obj_type}') IS NOT NULL",
            f"    DROP {drop_kw} {full}",
            "GO",
            "",
        ]
    )


def _drop_module_sql(schema: str, name: str, kind: str) -> str:
    full = f"{qident(schema)}.{qident(name)}"
    return f"PRINT N'Dropping {full}'\nGO\n{_drop_module_core(schema, name, kind)}"


def _module_session_options_from_entry(entry: Dict[str, Any]):
    if entry.get("uses_ansi_nulls") is None:
        return None
    return (bool(entry["uses_ansi_nulls"]), bool(entry.get("uses_quoted_identifier", True)))


def _fix_module_batch(entry: Dict[str, Any], kind: str) -> str:
    schema = entry.get("schema") or "dbo"
    name = entry.get("name") or ""
    defn = entry.get("definition") or ""
    full = f"{qident(schema)}.{qident(name)}"
    session_opts = _module_session_options_from_entry(entry)
    if defn.strip():
        body = format_module_sql_single(
            schema, name, defn, kind, session_options=session_opts
        ).strip()
    else:
        body = wrap_create_or_alter(
            schema, name, defn, kind, session_options=session_opts
        ).strip()
        body = body.replace("\nGO\n", "\n").strip()
    return "\n".join(
        [
            f"PRINT N'Fixing {full}'",
            "GO",
            _drop_module_core(schema, name, kind).strip(),
            body,
            "GO",
            "",
        ]
    )


def _module_category(kind: str) -> str:
    return {"PROC": "PROCEDURE", "VIEW": "VIEW", "FUNCTION": "FUNCTION"}.get(
        kind, kind
    )


def _module_object_name(entry: Dict[str, Any]) -> str:
    schema = entry.get("schema") or "dbo"
    name = entry.get("name") or ""
    return f"{schema}.{name}"


def generate_repair_items(
    diff_report: Dict[str, Any],
    source_catalog: Dict[str, Any],
    *,
    include_drop_extra: bool = True,
    dest_is_azure: bool = True,
) -> List[RepairItem]:
    """Structured repair steps for preview and per-item deploy."""
    items: List[RepairItem] = []

    schema_block = diff_report.get("principal_schemas") or {}
    for skip in schema_block.get("expected_skip") or []:
        name = skip.get("name", "")
        note = skip.get("note", "")
        sql = f"-- EXPECTED_SKIP: CREATE SCHEMA [{name}] — {note}\nGO\n"
        items.append(
            _repair_item(
                f"schema.skip.{name}",
                "SCHEMA",
                name,
                "SKIP",
                sql,
                expected_skip=True,
                reason=note,
            )
        )

    users_block = diff_report.get("users") or {}
    for skip in users_block.get("expected_skip") or []:
        name = skip.get("name", "")
        reason = EXPECTED_SKIP_REASONS.get(
            skip.get("reason", "windows_principal_azure"),
            skip.get("note", ""),
        )
        sql = f"-- EXPECTED_SKIP: CREATE USER [{name}] — {reason}\nGO\n"
        items.append(
            _repair_item(
                f"user.skip.{name}",
                "USER",
                name,
                "SKIP",
                sql,
                expected_skip=True,
                reason=reason,
            )
        )

    for missing_key in users_block.get("missing") or []:
        src_users = source_catalog.get("users") or {}
        entry = src_users.get(missing_key)
        if not entry:
            for k, v in src_users.items():
                if k.lower() == missing_key:
                    entry = v
                    break
        if not entry:
            continue
        name = entry.get("name", missing_key)
        if dest_is_azure and (
            entry.get("windows") or is_windows_principal_name(name)
        ):
            reason = "Map Entra ID group/user on target; do not emit CREATE USER FROM WINDOWS on MI"
            sql = f"-- EXPECTED_SKIP: user [{name}] missing on target — {reason}\nGO\n"
            items.append(
                _repair_item(
                    f"user.missing.{missing_key}",
                    "USER",
                    name,
                    "SKIP",
                    sql,
                    expected_skip=True,
                    reason=reason,
                )
            )
        else:
            sql = f"-- TODO: create user [{name}] (Entra/external provider) on target\nGO\n"
            items.append(
                _repair_item(
                    f"user.missing.{missing_key}",
                    "USER",
                    name,
                    "CREATE",
                    sql,
                    expected_skip=False,
                    reason="Manual user mapping required",
                )
            )

    asm_diff = diff_report.get("assemblies") or {}
    asm_batches: Dict[str, str] = dict(source_catalog.get("assembly_batches") or {})

    for asm_name in asm_diff.get("missing") or []:
        if dest_is_azure and is_mi_blocked_framework_assembly_name(asm_name):
            reason = EXPECTED_SKIP_REASONS["clr_framework_policy_azure"]
            sql = f"-- EXPECTED_SKIP: CREATE ASSEMBLY [{asm_name}] — {reason}\nGO\n"
            items.append(
                _repair_item(
                    f"assembly.missing.{asm_name}",
                    "ASSEMBLY",
                    asm_name,
                    "SKIP",
                    sql,
                    expected_skip=True,
                    reason=reason,
                )
            )
            continue
        batch = asm_batches.get(asm_name)
        if batch:
            sql = f"PRINT N'Creating assembly [{asm_name}]'\nGO\n{batch}\nGO\n"
            items.append(
                _repair_item(
                    f"assembly.missing.{asm_name}",
                    "ASSEMBLY",
                    asm_name,
                    "CREATE",
                    sql,
                )
            )
        else:
            sql = (
                f"-- ASSEMBLY [{asm_name}] missing; re-run Compare on live source "
                f"to export CREATE ASSEMBLY\nGO\n"
            )
            items.append(
                _repair_item(
                    f"assembly.missing.{asm_name}",
                    "ASSEMBLY",
                    asm_name,
                    "CREATE",
                    sql,
                    reason="No CREATE ASSEMBLY batch in catalog",
                )
            )

    for skip in asm_diff.get("expected_skip") or []:
        name = skip.get("name", "")
        note = skip.get("note", "")
        sql = f"-- EXPECTED_SKIP: assembly [{name}] — {note}\nGO\n"
        items.append(
            _repair_item(
                f"assembly.skip.{name}",
                "ASSEMBLY",
                name,
                "SKIP",
                sql,
                expected_skip=True,
                reason=note,
            )
        )

    for bucket, kind in (
        ("procedures", "PROC"),
        ("views", "VIEW"),
        ("functions", "FUNCTION"),
    ):
        mod_diff = diff_report.get(bucket) or {}
        src_mods = source_catalog.get(bucket) or {}
        category = _module_category(kind)
        keys_to_fix = list(mod_diff.get("missing") or [])
        keys_to_fix.extend(d.get("key") for d in mod_diff.get("different") or [])

        for key in keys_to_fix:
            entry = src_mods.get(key)
            if not entry:
                continue
            skip_note = None
            for d in mod_diff.get("different") or []:
                if d.get("key") == key and (
                    d.get("expected_skip_note") or d.get("expected_skip_reason")
                ):
                    skip_note = d.get("expected_skip_note") or EXPECTED_SKIP_REASONS.get(
                        d.get("expected_skip_reason", ""),
                        d.get("expected_skip_reason", ""),
                    )
                    break
            if dest_is_azure and not skip_note:
                reason = is_azure_nonportable_module(entry)
                if reason:
                    skip_note = EXPECTED_SKIP_REASONS.get(reason, reason)
            obj = _module_object_name(entry)
            if skip_note:
                sql = f"-- EXPECTED_SKIP: {key} — {skip_note}\nGO\n"
                items.append(
                    _repair_item(
                        key,
                        category,
                        obj,
                        "SKIP",
                        sql,
                        expected_skip=True,
                        reason=skip_note,
                    )
                )
                continue
            action = "CREATE" if key in (mod_diff.get("missing") or []) else "ALTER"
            items.append(
                _repair_item(
                    key,
                    category,
                    obj,
                    action,
                    _fix_module_batch(entry, kind),
                )
            )

        for skip in mod_diff.get("expected_skip") or []:
            key = skip.get("key", "")
            if key not in keys_to_fix:
                note = skip.get("note", "")
                sql = f"-- EXPECTED_SKIP: {key} — {note}\nGO\n"
                entry = src_mods.get(key) or {}
                items.append(
                    _repair_item(
                        key,
                        category,
                        _module_object_name(entry) if entry else key,
                        "SKIP",
                        sql,
                        expected_skip=True,
                        reason=note,
                    )
                )

    if include_drop_extra:
        for bucket, kind in (
            ("procedures", "PROC"),
            ("views", "VIEW"),
            ("functions", "FUNCTION"),
        ):
            mod_diff = diff_report.get(bucket) or {}
            category = _module_category(kind)
            for key in mod_diff.get("extra") or []:
                parts = key.split(".", 2)
                if len(parts) >= 3:
                    schema, name = parts[1], parts[2]
                else:
                    schema, name = "dbo", key
                obj = f"{schema}.{name}"
                sql = (
                    _drop_module_sql(schema, name, kind)
                    + f"-- Extra on target only: {key}\n"
                )
                items.append(
                    _repair_item(key, category, obj, "DROP", sql)
                )

    perm_diff = diff_report.get("permissions") or {}
    perm_batches = list(perm_diff.get("missing") or [])
    if not perm_batches and not (perm_diff.get("missing_count")):
        perm_batches = list(source_catalog.get("permission_batches") or [])
    if perm_batches:
        items.append(
            _repair_item(
                "permission.header",
                "PERMISSION",
                "(database permissions)",
                "ALTER",
                "PRINT N'Applying database permissions from source'\nGO\n",
            )
        )
        for idx, batch in enumerate(perm_batches):
            first_line = (batch.splitlines()[0] if batch else "")[:120]
            if dest_is_azure and is_windows_principal_batch(batch):
                reason = EXPECTED_SKIP_REASONS["windows_principal_azure"]
                sql = f"-- EXPECTED_SKIP: {first_line} — {reason}\nGO\n"
                items.append(
                    _repair_item(
                        f"permission.{idx}",
                        "PERMISSION",
                        first_line,
                        "SKIP",
                        sql,
                        expected_skip=True,
                        reason=reason,
                    )
                )
                continue
            sql = f"{batch.strip()}\nGO\n"
            items.append(
                _repair_item(
                    f"permission.{idx}",
                    "PERMISSION",
                    first_line,
                    "ALTER",
                    sql,
                )
            )

    return items


def repair_items_to_sql(
    items: List[RepairItem],
    *,
    source_label: str = "source",
    target_label: str = "target",
) -> str:
    """Concatenate structured items into a single audit script."""
    chunks: List[str] = [_sql_compare_header(source_label, target_label)]
    for item in items:
        batches = [b.strip() for b in (item.get("sql_batches") or []) if b and str(b).strip()]
        if batches:
            chunks.append("\nGO\n".join(batches))
        else:
            reason = item.get("reason") or ""
            chunks.append(
                f"-- {item.get('category')} {item.get('object_name')} "
                f"({item.get('action')}) {reason}\nGO\n"
            )
    return "\n".join(chunks)


def generate_repair_script(
    diff_report: Dict[str, Any],
    source_catalog: Dict[str, Any],
    *,
    target_label: str = "target",
    source_label: str = "source",
    include_drop_extra: bool = True,
    dest_is_azure: bool = True,
) -> str:
    """Build a fix script from compare output and live source catalog definitions."""
    items = generate_repair_items(
        diff_report,
        source_catalog,
        include_drop_extra=include_drop_extra,
        dest_is_azure=dest_is_azure,
    )
    return repair_items_to_sql(
        items, source_label=source_label, target_label=target_label
    )


def write_repair_script(
    sql_text: str,
    output_dir: Path,
    *,
    filename: Optional[str] = None,
) -> Path:
    """Write repair SQL to *output_dir* (schema_compare_output run folder or legacy meta)."""
    output_dir = Path(output_dir)
    meta = output_dir / "schema" / "meta"
    if meta.is_dir() or (output_dir / "schema").is_dir():
        meta.mkdir(parents=True, exist_ok=True)
        dest_dir = meta
    else:
        output_dir.mkdir(parents=True, exist_ok=True)
        dest_dir = output_dir
    fname = filename or f"repair_{utc_ts_compact()}.sql"
    out_path = dest_dir / fname
    out_path.write_text(sql_text, encoding="utf-8")
    return out_path
